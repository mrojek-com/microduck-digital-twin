READ_ADDR: int = 124
READ_LEN: int = 12
SLOW_READ_ADDR: int = 144
SLOW_READ_LEN: int = 3
RAD_PER_SEC_PER_COUNT: float = 0.229 * (2.0 * math.pi / 60.0)  # ~0.0239808239 rad/s
ENCODER_COUNTS_PER_REV: int = 4096
RAD_PER_COUNT: float = (2.0 * math.pi) / ENCODER_COUNTS_PER_REV  # ~0.0015339808 rad
PWM_MAX_COUNTS: int = 885
VOLTS_PER_COUNT: float = 0.1
STALE_RUN_WARN: int = 25
IMU_BLOCK_LEN: int = 12


def quantize_xl330_position_rad(angle_rad: float) -> float:
    """Quantize joint angle to XL330 12-bit contactless magnetic encoder (4096 counts/rev)."""
    if not math.isfinite(angle_rad):
        return 0.0
    counts = round(angle_rad / RAD_PER_COUNT)
    return counts * RAD_PER_COUNT


def quantize_xl330_velocity_rad_s(vel_rad_s: float) -> float:
    """Quantize angular velocity to XL330 register 128 (`0.229 rpm/count`)."""
    if not math.isfinite(vel_rad_s):
        return 0.0
    counts = round(vel_rad_s / RAD_PER_SEC_PER_COUNT)
    return counts * RAD_PER_SEC_PER_COUNT


@dataclass
class StaleImuTracker:
    """
    Matches `duck-control/src/bus.rs::StaleImuTracker`.
    Detects an IMU board that answers with identical 12-byte SFLP blocks without refreshing.
    Warns when `run >= STALE_RUN_WARN` (25 ticks = 0.5 s at 50 Hz).
    """

    last_block: Optional[bytes] = None
    total_stale: int = 0
    current_run: int = 0

    def observe(self, block12: bytes) -> int:
        if len(block12) != IMU_BLOCK_LEN:
            raise ValueError(f"Expected {IMU_BLOCK_LEN}-byte IMU block, got {len(block12)}")
        if self.last_block is not None and self.last_block == block12:
            self.total_stale += 1
            self.current_run += 1
        else:
            self.current_run = 0
        self.last_block = bytes(block12)
        return self.current_run

    @property
    def is_frozen_warn(self) -> bool:
        return self.current_run >= STALE_RUN_WARN


class Xl330BusSimulator:
    """
    Register-level XL330-M288-T bus & thermal/voltage physics (`duck-control/src/bus.rs` & `Rhoban/bam`):
    - Fast Sync Read (`0x8A`, 12 bytes at 124..136): `present_pwm`, `present_current`, `present_velocity`, `present_position`
    - Slow Sensors (`144..146`, 3 bytes at 1 Hz): `present_input_voltage` (0.1 V counts), `present_temperature` (1 degC counts)
    - 2S Li-Ion voltage sag (8.4 V nominal -> 6.8 V brownout under load) + Joule heating (`I^2 * R`) with 70 C thermal derating.
    """

    def __init__(self, nominal_volts: float = 8.2, ambient_temp_c: float = 31.0) -> None:
        self.nominal_volts = nominal_volts
        self.ambient_temp_c = ambient_temp_c
        self.bus_volts = nominal_volts
        self.temps_c: List[float] = [ambient_temp_c] * NUM_JOINTS
        self.pwm_counts: List[int] = [0] * NUM_JOINTS
        self.currents_ma: List[float] = [80.0] * NUM_JOINTS
        self.quantized_positions: List[float] = list(DEFAULT_POSITION)
        self.quantized_velocities: List[float] = [0.0] * NUM_JOINTS
        self.thermal_overload_joints: List[int] = []
        self.stale_imu = StaleImuTracker()

    def step_bus(
        self,
        target_positions15: Sequence[float],
        actual_positions15: Sequence[float],
        actual_velocities15: Sequence[float],
        dt: float = 0.02,
        kp_gain: int = 200,
    ) -> Dict[str, object]:
        total_current_a = 0.0
        self.thermal_overload_joints = []

        for i in range(NUM_JOINTS):
            q_pos = quantize_xl330_position_rad(actual_positions15[i])
            q_vel = quantize_xl330_velocity_rad_s(actual_velocities15[i])
            self.quantized_positions[i] = q_pos
            self.quantized_velocities[i] = q_vel

            err_rad = target_positions15[i] - q_pos
            # PWM command proportional to position error and velocity back-EMF
            raw_pwm = (err_rad * (kp_gain / 200.0) * 620.0) - (q_vel * 28.0)
            # Thermal derating above 70 degC (XL330 Shutdown/Derating threshold)
            if self.temps_c[i] >= 70.0:
                raw_pwm *= 0.25
                self.thermal_overload_joints.append(i)
            pwm_c = int(max(-PWM_MAX_COUNTS, min(PWM_MAX_COUNTS, round(raw_pwm))))
            self.pwm_counts[i] = pwm_c

            # Current draw in mA (stall torque + dynamic load)
            curr_ma = min(1450.0, 65.0 + abs(pwm_c) * 1.15 + abs(err_rad) * 420.0)
            self.currents_ma[i] = round(curr_ma, 1)
            total_current_a += curr_ma / 1000.0

            # Joule heating (I^2 * R_coil) minus Newtonian cooling to ambient
            i_amp = curr_ma / 1000.0
            d_temp = ((i_amp * i_amp) * 6.8 - (self.temps_c[i] - self.ambient_temp_c) * 0.12) * dt
            self.temps_c[i] = max(self.ambient_temp_c, min(88.0, self.temps_c[i] + d_temp))

        # 2S Li-Ion internal resistance sag (R_internal ~ 0.14 Ohm)
        sag_v = total_current_a * 0.14
        raw_v = max(6.4, min(8.4, self.nominal_volts - sag_v))
        # Quantize to 0.1 V counts as reported by register 144 (`VOLTS_PER_COUNT = 0.1`)
        self.bus_volts = round(round(raw_v / VOLTS_PER_COUNT) * VOLTS_PER_COUNT, 1)

        # Back-EMF max no-load velocity scales linearly with bus voltage (nominal ~10.2 rad/s at 8.2V)
        max_vel_rad_s = 10.2 * (self.bus_volts / 8.2)

        return {
            "quantized_positions": list(self.quantized_positions),
            "quantized_velocities": list(self.quantized_velocities),
            "pwm_counts": list(self.pwm_counts),
            "currents_ma": list(self.currents_ma),
            "bus_volts": self.bus_volts,
            "temps_c": [ float(round(t)) for t in self.temps_c ],
            "max_vel_rad_s": round(max_vel_rad_s, 3),
            "thermal_overload_joints": list(self.thermal_overload_joints),
        }

    def pack_fast_sync_read_block(self, joint_index: int) -> bytes:
        """
        Pack the exact 12-byte register block `124..136` (`<hhii`):
        - 124..126: `present_pwm` (`i16`)
        - 126..128: `present_current` (`i16`, mA)
        - 128..132: `present_velocity` (`i32`, in `0.229 rpm` counts)
        - 132..136: `present_position` (`i32`, in `4096 counts/rev`)
        """
        pwm_i16 = int(max(-885, min(885, self.pwm_counts[joint_index])))
        cur_i16 = int(max(-2000, min(2000, round(self.currents_ma[joint_index]))))
        vel_cnt = int(round(self.quantized_velocities[joint_index] / RAD_PER_SEC_PER_COUNT))
        pos_cnt = int(round(self.quantized_positions[joint_index] / RAD_PER_COUNT)) + 2048
        return struct.pack("<hhii", pwm_i16, cur_i16, vel_cnt, pos_cnt)

    def pack_slow_sensors_block(self, joint_index: int) -> bytes:
        """
        Pack the exact 3-byte register block `144..146` (`<HB`):
        - 144..146: `present_input_voltage` (`u16`, `0.1 V` counts)
        - 146..147: `present_temperature` (`u8`, `1 degC` counts)
        """
        v_cnt = int(max(0, min(65535, round(self.bus_volts / VOLTS_PER_COUNT))))
        t_cnt = int(max(0, min(255, round(self.temps_c[joint_index]))))
        return struct.pack("<HB", v_cnt, t_cnt)


