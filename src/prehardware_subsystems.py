class StopAndVoteMapper:
    """
    Implements the core invariant of `maploc/src/lib.rs`:
    "The sensor is a cane, not a lidar: 64 zones over 45 deg, most valid returns inside a metre.
    A stop is the unit of mapping: frames from one standing place are voted into one rigid keyframe."
    """

    def __init__(self, grid_size: int = 21, cell_res_m: float = 0.15) -> None:
        self.grid_size = grid_size
        self.cell_res_m = cell_res_m
        self.stop_ticks: int = 0
        self.stop_confirm_ticks: int = 5  # 100 ms standing stillness to begin voting
        self.vote_accumulator: List[List[float]] = [[] for _ in range(64)]
        self.keyframes: List[Dict[str, object]] = []
        # Log-odds occupancy grid: 0.0 = unknown, >0 = obstacle, <0 = free
        self.grid_log_odds: List[List[float]] = [
            [0.0 for _ in range(grid_size)] for _ in range(grid_size)
        ]

    def observe_tick(
        self,
        odom_xy: Sequence[float],
        odom_yaw: float,
        speed_m_s: float,
        gyro_norm_rad_s: float,
        tof_zones64_m: Sequence[float],
    ) -> Dict[str, object]:
        if len(tof_zones64_m) != 64:
            raise ValueError("Expected 64 ToF zones (8x8)")

        is_stopped = speed_m_s < 0.015 and gyro_norm_rad_s < 0.08
        committed_keyframe = False

        if is_stopped:
            self.stop_ticks += 1
            for z_idx, dist_m in enumerate(tof_zones64_m):
                if 0.08 <= dist_m <= 1.20:
                    self.vote_accumulator[z_idx].append(float(dist_m))

            # Once 8 frames are voted at a stop, lock a rigid keyframe into the occupancy grid
            if self.stop_ticks == self.stop_confirm_ticks + 8:
                voted_scan: List[Optional[float]] = []
                for bucket in self.vote_accumulator:
                    if len(bucket) >= 5:
                        s_bucket = sorted(bucket)
                        med = s_bucket[len(s_bucket) // 2]
                        # Reject low-agreement cells per Claude Endgegner review
                        spread = s_bucket[-1] - s_bucket[0]
                        voted_scan.append(med if spread < 0.08 else None)
                    else:
                        voted_scan.append(None)

                self._splat_keyframe_to_grid(odom_xy, odom_yaw, voted_scan)
                self.keyframes.append(
                    {
                        "id": len(self.keyframes),
                        "pose_xy": [round(float(odom_xy[0]), 3), round(float(odom_xy[1]), 3)],
                        "yaw_rad": round(float(odom_yaw), 3),
                        "valid_zones": sum(1 for v in voted_scan if v is not None),
                    }
                )
                committed_keyframe = True
        else:
            # Moving: clear stop accumulator so motion-smeared ToF frames are never inked
            self.stop_ticks = 0
            self.vote_accumulator = [[] for _ in range(64)]

        return {
            "is_stopped": is_stopped,
            "stop_ticks": self.stop_ticks,
            "committed_keyframe": committed_keyframe,
            "keyframe_count": len(self.keyframes),
        }

    def _splat_keyframe_to_grid(
        self, odom_xy: Sequence[float], odom_yaw: float, voted_scan64: Sequence[Optional[float]]
    ) -> None:
        half = self.grid_size // 2
        for c in range(8):
            # Bottom row (row 6..7) sees floor; middle rows (row 2..5) see obstacles
            for r in range(2, 6):
                dist = voted_scan64[r * 8 + c]
                if dist is None:
                    continue
                az_off = ((c - 3.5) / 3.5) * (math.radians(22.5))
                ray_yaw = odom_yaw - az_off
                # Mark intermediate cells along ray as free (-0.35)
                steps = max(1, int(dist / (self.cell_res_m * 0.5)))
                for s in range(1, steps):
                    d_free = (s / steps) * dist
                    fx = odom_xy[0] + math.cos(ray_yaw) * d_free
                    fy = odom_xy[1] + math.sin(ray_yaw) * d_free
                    gx = half + int(round(fx / self.cell_res_m))
                    gy = half + int(round(fy / self.cell_res_m))
                    if 0 <= gx < self.grid_size and 0 <= gy < self.grid_size:
                        self.grid_log_odds[gy][gx] = max(-3.0, self.grid_log_odds[gy][gx] - 0.35)

                # Mark endpoint as obstacle (+0.85) if inside 1.0 m range
                if dist < 1.05:
                    ox = odom_xy[0] + math.cos(ray_yaw) * dist
                    oy = odom_xy[1] + math.sin(ray_yaw) * dist
                    gx = half + int(round(ox / self.cell_res_m))
                    gy = half + int(round(oy / self.cell_res_m))
                    if 0 <= gx < self.grid_size and 0 <= gy < self.grid_size:
                        self.grid_log_odds[gy][gx] = min(3.5, self.grid_log_odds[gy][gx] + 0.85)


