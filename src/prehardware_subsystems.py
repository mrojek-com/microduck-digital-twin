# Pillar 5: 6-Axis Gamepad IMU Filter, 12 deg/s Clone Bias & Dead-Radio Auditor
# (`pad-imu/src/lib.rs` & `padd/src/tap.rs`)
# =============================================================================

GRAVITY_GAIN: float = 2.0
GRAVITY_BAND_MIN: float = 0.85
GRAVITY_BAND_MAX: float = 1.15
STILL_WINDOW_S: float = 0.5
STILL_SPREAD_DPS: float = 3.0
MAX_DT_S: float = 0.05
CLONE_UNINITIALIZED_Z_DRIFT_DPS: float = 12.0


class PadImuFilter:
    """
    Clean-room implementation of `pad-imu/src/lib.rs` & `padd/src/tap.rs`:
    - 6-axis complementary filter (`GRAVITY_GAIN = 2.0`, `GRAVITY_BAND = 0.85..=1.15 g`)
    - Stillness-window gyro bias calibrator (`STILL_WINDOW_S = 0.5 s`, `STILL_SPREAD_DPS = 3.0 deg/s`)
      that automatically discovers and subtracts the Switch Pro clone's 12 deg/s resting Z-rate bias.
    - Dead-Radio `SYN_DROPPED` / stale-evdev detector: flags when `padd` keeps streaming 50 Hz cached
      intents while the underlying Bluetooth radio has stopped delivering fresh kernel evdev frames.
    """

    def __init__(self) -> None:
        self.bias_dps: Optional[List[float]] = None
        self._win_since_s: Optional[float] = None
        self._win_min: List[float] = [float("inf")] * 3
        self._win_max: List[float] = [float("-inf")] * 3
        self._win_sum: List[float] = [0.0, 0.0, 0.0]
        self._win_count: int = 0
        self._last_time_s: Optional[float] = None
        self.rpy_rad: List[float] = [0.0, 0.0, 0.0]  # roll, pitch, yaw
        self.socket_dropped: int = 0
        self.last_evdev_seq: int = 0
        self.stale_radio_ticks: int = 0

    def _reset_still_window(self) -> None:
        self._win_since_s = None
        self._win_min = [float("inf")] * 3
        self._win_max = [float("-inf")] * 3
        self._win_sum = [0.0, 0.0, 0.0]
        self._win_count = 0

    def push_sample(
        self,
        accel_g: Sequence[float],
        raw_gyro_dps: Sequence[float],
        at_s: float,
        evdev_seq: Optional[int] = None,
        syn_dropped: bool = False,
    ) -> Dict[str, object]:
        if syn_dropped:
            self.socket_dropped += 1
            self._reset_still_window()

        if evdev_seq is not None:
            if evdev_seq == self.last_evdev_seq:
                self.stale_radio_ticks += 1
            else:
                self.stale_radio_ticks = 0
                self.last_evdev_seq = evdev_seq

        ax, ay, az = float(accel_g[0]), float(accel_g[1]), float(accel_g[2])
        gx, gy, gz = float(raw_gyro_dps[0]), float(raw_gyro_dps[1]), float(raw_gyro_dps[2])
        acc_norm = math.sqrt(ax * ax + ay * ay + az * az)
        gravity_ok = GRAVITY_BAND_MIN <= acc_norm <= GRAVITY_BAND_MAX

        # Stillness gyro-bias detector (`pad-imu/src/lib.rs::Bias::observe`)
        if not gravity_ok:
            self._reset_still_window()
        else:
            if self._win_since_s is None:
                self._win_since_s = at_s
            rates = (gx, gy, gz)
            spread_ok = True
            for axis in range(3):
                self._win_min[axis] = min(self._win_min[axis], rates[axis])
                self._win_max[axis] = max(self._win_max[axis], rates[axis])
                self._win_sum[axis] += rates[axis]
                if (self._win_max[axis] - self._win_min[axis]) > STILL_SPREAD_DPS:
                    spread_ok = False
            self._win_count += 1

            if not spread_ok:
                self._reset_still_window()
            elif (at_s - self._win_since_s) >= STILL_WINDOW_S and self._win_count >= 5:
                self.bias_dps = [self._win_sum[i] / self._win_count for i in range(3)]
                self._reset_still_window()

        # Interval clamp (`MAX_DT_S = 0.05 s`)
        if self._last_time_s is None:
            dt = 0.0
        else:
            raw_dt = at_s - self._last_time_s
            dt = raw_dt if (0.0 < raw_dt <= MAX_DT_S) else 0.0
        self._last_time_s = at_s

        bx, by, bz = self.bias_dps if self.bias_dps is not None else (0.0, 0.0, 0.0)
        wx = math.radians(gx - bx)
        wy = math.radians(gy - by)
        wz = math.radians(gz - bz)

        # Integrate gyro
        self.rpy_rad[0] += wx * dt
        self.rpy_rad[1] += wy * dt
        self.rpy_rad[2] += wz * dt

        # Pull roll & pitch toward gravity when inside GRAVITY_BAND (`GRAVITY_GAIN = 2.0`)
        if gravity_ok and acc_norm > 1e-6 and dt > 0.0:
            acc_roll = math.atan2(ay, az)
            acc_pitch = math.atan2(-ax, math.sqrt(ay * ay + az * az))
            alpha = min(1.0, GRAVITY_GAIN * dt)
            self.rpy_rad[0] += (acc_roll - self.rpy_rad[0]) * alpha
            self.rpy_rad[1] += (acc_pitch - self.rpy_rad[1]) * alpha

        # Dead-radio stale stream trap: `robotd` deadman is 250ms (12.5 ticks at 50Hz),
        # so if `padd` repeats cached intents for >=13 ticks while `evdev_seq` is frozen,
        # the radio link is dead even though `robotd` has not tripped deadman!
        dead_radio_trap = self.stale_radio_ticks >= 13

        return {
            "rpy_rad": list(self.rpy_rad),
            "bias_dps": list(self.bias_dps) if self.bias_dps is not None else None,
            "calibrated": self.bias_dps is not None,
            "gravity_ok": gravity_ok,
            "socket_dropped": self.socket_dropped,
            "stale_radio_ticks": self.stale_radio_ticks,
            "dead_radio_trap_detected": dead_radio_trap,
        }
