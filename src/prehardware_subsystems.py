def quat_yaw(quat_wxyz: Sequence[float]) -> float:
    w, x, y, z = quat_wxyz
    siny_cosp = 2.0 * (w * z + x * y)
    cosy_cosp = 1.0 - 2.0 * (y * y + z * z)
    return math.atan2(siny_cosp, cosy_cosp)


class ContactOdometry:
    """
    Exact contact-anchor odometry estimator (`odometry/src/lib.rs`).
    Tracks the active sole contact anchor across `alpha16`, `alpha4`, or `v15`
    sole points and switches when another sole point drops below `SWITCH_MARGIN`
    (-0.010 m) for `SWITCH_CONFIRM_TICKS` (2 consecutive 50 Hz ticks = 40 ms).
    """

    def __init__(
        self,
        anchor_set: str = "alpha16",
        fk: Optional[ForwardKinematics] = None,
        quantize_encoders: bool = False,
    ) -> None:
        if anchor_set not in ANCHOR_SETS:
            raise ValueError(f"Unknown anchor_set: {anchor_set}")
        self.anchor_set_name = anchor_set
        self.left_points, self.right_points = ANCHOR_SETS[anchor_set]
        self.fk = fk or ForwardKinematics()
        self.quantize_encoders = quantize_encoders

        self.anchor_foot: int = LEFT_FOOT
        self.anchor_index: int = 0
        self.anchor_local: Tuple[float, float, float] = (0.0, 0.0, 0.0)
        self.anchor_xy: List[float] = [0.0, 0.0]
        self.position: List[float] = [0.0, 0.0, 0.0]
        self.yaw: float = 0.0
        self.pending: Optional[Tuple[int, int, Tuple[float, float, float], List[float]]] = None
        self.pending_ticks: int = 0
        self.switches: int = 0
        self.needs_init: bool = True

    def _foot_poses_in_trunk(
        self, joints15: Sequence[float]
    ) -> Tuple[Tuple[List[List[float]], List[float]], Tuple[List[List[float]], List[float]]]:
        eff_joints = (
            [quantize_xl330_position_rad(a) for a in joints15]
            if self.quantize_encoders
            else list(joints15)
        )
        poses = self.fk.solve_bodies(eff_joints)
        # Body 5 is left_ankle (foot), Body 14 is right_ankle (foot)
        # Apply sole site offset so the foot site sits on the sole bottom plane
        left_r, left_t = poses[5]
        right_r, right_t = poses[14]
        sole_offset = [0.0, 0.0, -0.022]
        lt_off = _mat3_vec(left_r, sole_offset)
        rt_off = _mat3_vec(right_r, sole_offset)
        left_site = (left_r, [left_t[0] + lt_off[0], left_t[1] + lt_off[1], left_t[2] + lt_off[2]])
        right_site = (right_r, [right_t[0] + rt_off[0], right_t[1] + rt_off[1], right_t[2] + rt_off[2]])
        return left_site, right_site

    @staticmethod
    def _transform_site_point(
        site_pose: Tuple[List[List[float]], List[float]], pt_local: Sequence[float]
    ) -> List[float]:
        r, t = site_pose
        rot_pt = _mat3_vec(r, pt_local)
        return [t[0] + rot_pt[0], t[1] + rot_pt[1], t[2] + rot_pt[2]]

    def _reproject(
        self,
        rot_world_from_trunk: List[List[float]],
        feet: Tuple[Tuple[List[List[float]], List[float]], Tuple[List[List[float]], List[float]]],
    ) -> None:
        contact_in_trunk = self._transform_site_point(feet[self.anchor_foot], self.anchor_local)
        contact_world = _mat3_vec(rot_world_from_trunk, contact_in_trunk)
        self.position = [
            self.anchor_xy[0] - contact_world[0],
            self.anchor_xy[1] - contact_world[1],
            -contact_world[2],
        ]

    def _lowest_corner(
        self,
        rot_world_from_trunk: List[List[float]],
        feet: Tuple[Tuple[List[List[float]], List[float]], Tuple[List[List[float]], List[float]]],
    ) -> Optional[Tuple[int, int, Tuple[float, float, float], List[float]]]:
        lowest_z = SWITCH_MARGIN  # Must be strictly below -0.010 m in world Z
        best: Optional[Tuple[int, int, Tuple[float, float, float], List[float]]] = None
        for foot_idx, pts in ((LEFT_FOOT, self.left_points), (RIGHT_FOOT, self.right_points)):
            for pt_idx, corner in enumerate(pts):
                in_trunk = self._transform_site_point(feet[foot_idx], corner)
                in_world = _mat3_vec(rot_world_from_trunk, in_trunk)
                wx = self.position[0] + in_world[0]
                wy = self.position[1] + in_world[1]
                wz = self.position[2] + in_world[2]
                if wz < lowest_z:
                    lowest_z = wz
                    best = (foot_idx, pt_idx, corner, [wx, wy])
        return best

    def update(self, joints15: Sequence[float], quat_wxyz: Sequence[float]) -> Dict[str, object]:
        rot = _quat_to_rot3(quat_wxyz)
        feet = self._foot_poses_in_trunk(joints15)

        if self.needs_init:
            anchor_world = _mat3_vec(rot, feet[self.anchor_foot][1])
            self.anchor_xy = [anchor_world[0], anchor_world[1]]
            self.needs_init = False

        self._reproject(rot, feet)

        cand = self._lowest_corner(rot, feet)
        if cand is None:
            self.pending = None
            self.pending_ticks = 0
        else:
            c_foot, c_idx, c_local, c_world_xy = cand
            if self.pending is not None and self.pending[0] == c_foot:
                self.pending_ticks += 1
                self.pending = (c_foot, c_idx, c_local, c_world_xy)
            else:
                self.pending = (c_foot, c_idx, c_local, c_world_xy)
                self.pending_ticks = 1

            if self.pending_ticks >= SWITCH_CONFIRM_TICKS:
                foot, idx, local, world_xy = self.pending
                self.pending = None
                self.pending_ticks = 0
                self.anchor_foot = foot
                self.anchor_index = idx
                self.anchor_local = local
                # Continuous handoff: corner keeps the world X/Y it already had
                self.anchor_xy = list(world_xy)
                self.switches += 1
                self._reproject(rot, feet)

        self.yaw = quat_yaw(quat_wxyz)
        return {
            "anchor_set": self.anchor_set_name,
            "position": list(self.position),
            "yaw": self.yaw,
            "anchor_foot": "left" if self.anchor_foot == LEFT_FOOT else "right",
            "anchor_index": self.anchor_index,
            "anchor_xy": list(self.anchor_xy),
            "switches": self.switches,
        }


